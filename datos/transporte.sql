-- Red de transporte público: esquema y datos (MariaDB)
CREATE DATABASE IF NOT EXISTS transporte CHARACTER SET utf8mb4;
USE transporte;

DROP TABLE IF EXISTS viaje, parada_linea, linea, vehiculo, parada;

CREATE TABLE parada (id INT PRIMARY KEY, nombre VARCHAR(60) NOT NULL, zona INT NOT NULL);
CREATE TABLE vehiculo (id INT PRIMARY KEY, matricula VARCHAR(10) NOT NULL, capacidad INT NOT NULL);
CREATE TABLE linea (id INT PRIMARY KEY, nombre VARCHAR(60) NOT NULL, vehiculo_id INT NOT NULL,
  FOREIGN KEY (vehiculo_id) REFERENCES vehiculo(id));
CREATE TABLE parada_linea (linea_id INT NOT NULL, parada_id INT NOT NULL, orden INT NOT NULL,
  minutos_desde_anterior INT NOT NULL, PRIMARY KEY (linea_id, parada_id),
  FOREIGN KEY (linea_id) REFERENCES linea(id), FOREIGN KEY (parada_id) REFERENCES parada(id));
CREATE TABLE viaje (id INT PRIMARY KEY, linea_id INT NOT NULL, fecha DATETIME NOT NULL,
  pasajeros INT NOT NULL, FOREIGN KEY (linea_id) REFERENCES linea(id));

